-- ---------- PROFILES ----------

DROP POLICY IF EXISTS "Users can view all profiles." ON public.profiles;
CREATE POLICY "Users can view all profiles."
ON public.profiles FOR SELECT
TO authenticated
USING (true);

DROP POLICY IF EXISTS "Users can update their own profile." ON public.profiles;
CREATE POLICY "Users can update their own profile."
ON public.profiles FOR UPDATE
TO authenticated
USING (auth.uid() = id)
WITH CHECK (auth.uid() = id);

DROP POLICY IF EXISTS "Users can delete their own profile." ON public.profiles;
CREATE POLICY "Users can delete their own profile."
ON public.profiles FOR DELETE
TO authenticated
USING (auth.uid() = id);

-- Permitir INSERT do trigger (service role) e do próprio usuário
DROP POLICY IF EXISTS "Service role can insert profiles." ON public.profiles;
CREATE POLICY "Service role can insert profiles."
ON public.profiles FOR INSERT
WITH CHECK (true);

-- ---------- INTERACTIONS ----------

DROP POLICY IF EXISTS "Users can insert their own interactions." ON public.interactions;
CREATE POLICY "Users can insert their own interactions."
ON public.interactions FOR INSERT
TO authenticated
WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can only see their own interactions." ON public.interactions;
CREATE POLICY "Users can only see their own interactions."
ON public.interactions FOR SELECT
TO authenticated
USING (auth.uid() = user_id);

-- ---------- MATCHES ----------

-- Remover policies conflitantes anteriores
DROP POLICY IF EXISTS "Block all client-side modifications on matches" ON public.matches;
DROP POLICY IF EXISTS "Users can view their own matches." ON public.matches;
DROP POLICY IF EXISTS "Block client-side insert on matches" ON public.matches;
DROP POLICY IF EXISTS "Block client-side update on matches" ON public.matches;
DROP POLICY IF EXISTS "Block client-side delete on matches" ON public.matches;

-- SELECT: Usuário pode ver seus próprios matches
CREATE POLICY "Users can view their own matches."
ON public.matches FOR SELECT
TO authenticated
USING (auth.uid() = user1_id OR auth.uid() = user2_id);

-- Bloquear INSERT/UPDATE/DELETE direto do cliente
-- (matches são criados pela função handle_interaction com SECURITY DEFINER)
CREATE POLICY "Block client-side insert on matches"
ON public.matches FOR INSERT
TO authenticated
WITH CHECK (false);

CREATE POLICY "Block client-side update on matches"
ON public.matches FOR UPDATE
TO authenticated
USING (false)
WITH CHECK (false);

CREATE POLICY "Block client-side delete on matches"
ON public.matches FOR DELETE
TO authenticated
USING (false);

-- ---------- MESSAGES ----------

DROP POLICY IF EXISTS "Users can view messages in their own matches." ON public.messages;
CREATE POLICY "Users can view messages in their own matches."
ON public.messages FOR SELECT
TO authenticated
USING (
  EXISTS (
    SELECT 1 FROM public.matches
    WHERE matches.id = messages.match_id
      AND (matches.user1_id = auth.uid() OR matches.user2_id = auth.uid())
  )
);

DROP POLICY IF EXISTS "Users can insert messages in their own matches." ON public.messages;
CREATE POLICY "Users can insert messages in their own matches."
ON public.messages FOR INSERT
TO authenticated
WITH CHECK (
  auth.uid() = sender_id
  AND EXISTS (
    SELECT 1 FROM public.matches
    WHERE matches.id = messages.match_id
      AND (matches.user1_id = auth.uid() OR matches.user2_id = auth.uid())
  )
);

