-- 6. TRIGGER: Auto-criar perfil quando um usuário se cadastra
-- =====================================================================

-- Dropar funções existentes para permitir alteração de assinatura
DROP FUNCTION IF EXISTS public.handle_new_user() CASCADE;
DROP FUNCTION IF EXISTS public.handle_interaction(uuid, uuid, text) CASCADE;
DROP FUNCTION IF EXISTS public.get_recommendations(uuid) CASCADE;
DROP FUNCTION IF EXISTS public.get_matches(uuid) CASCADE;
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.profiles (id, username)
  VALUES (
    NEW.id,
    COALESCE(NEW.raw_user_meta_data->>'preferred_username', NEW.email, NEW.id::text)
  )
  ON CONFLICT (id) DO NOTHING;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Dropar e recriar o trigger para garantir consistência
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

-- =====================================================================
-- 7. RPC: handle_interaction (SECURITY DEFINER)
--    Registra like/dislike e cria match se houver reciprocidade
-- =====================================================================
CREATE OR REPLACE FUNCTION handle_interaction(
  p_user_id uuid,
  p_target_user_id uuid,
  p_action text
)
RETURNS boolean AS $$
DECLARE
  is_match boolean := false;
BEGIN
  -- Inserir a interação
  INSERT INTO public.interactions (user_id, target_user_id, action)
  VALUES (p_user_id, p_target_user_id, p_action)
  ON CONFLICT (user_id, target_user_id) 
  DO UPDATE SET action = EXCLUDED.action, created_at = NOW();

  -- Se for 'like', verificar reciprocidade
  IF p_action = 'like' THEN
    IF EXISTS (
      SELECT 1
      FROM public.interactions
      WHERE user_id = p_target_user_id
        AND target_user_id = p_user_id
        AND action = 'like'
    ) THEN
      is_match := true;

      -- Inserir match (LEAST/GREATEST garante unicidade)
      INSERT INTO public.matches (user1_id, user2_id)
      SELECT
        LEAST(p_user_id, p_target_user_id),
        GREATEST(p_user_id, p_target_user_id)
      ON CONFLICT (user1_id, user2_id) DO NOTHING;
    END IF;
  END IF;

  RETURN is_match;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- =====================================================================
-- 8. RPC: get_recommendations (SECURITY DEFINER)
--    Retorna até 20 perfis recomendados com score baseado em
--    distância (60%) e interesses comuns (40%)
-- =====================================================================
CREATE OR REPLACE FUNCTION get_recommendations(current_user_id uuid)
RETURNS TABLE(
  id uuid,
  username text,
  full_name text,
  avatar_url text,
  bio text,
  interests text[],
  age integer,
  recommendation_score float
) AS $$
DECLARE
  current_user_location geography;
  max_distance float := 50000; -- 50km
BEGIN
  -- Obter localização do usuário atual
  SELECT p.location INTO current_user_location
  FROM public.profiles p
  WHERE p.id = current_user_id;

  RETURN QUERY
  WITH user_interests AS (
    SELECT p_inner.interests
    FROM public.profiles p_inner
    WHERE p_inner.id = current_user_id
  ),
  scores AS (
    SELECT
      p.id,
      p.username,
      p.full_name,
      p.avatar_url,
      p.bio,
      p.interests,
      EXTRACT(YEAR FROM AGE(p.birth_date))::integer AS age,
      CASE
        WHEN current_user_location IS NOT NULL AND p.location IS NOT NULL THEN
          (1 - LEAST(ST_Distance(current_user_location, p.location) / max_distance, 1.0))
        ELSE
          0.0
      END AS distance_score,
      count_common_elements(ui.interests, p.interests) AS interest_score
    FROM
      public.profiles p, user_interests ui
    WHERE
      p.id != current_user_id
      -- Excluir perfis já interagidos
      AND NOT EXISTS (
        SELECT 1 FROM public.interactions i
        WHERE i.user_id = current_user_id AND i.target_user_id = p.id
      )
      -- Excluir perfis que já são match
      AND NOT EXISTS (
        SELECT 1 FROM public.matches m
        WHERE (m.user1_id = current_user_id AND m.user2_id = p.id)
           OR (m.user2_id = current_user_id AND m.user1_id = p.id)
      )
  )
  SELECT
    s.id,
    s.username,
    s.full_name,
    s.avatar_url,
    s.bio,
    s.interests,
    s.age,
    (COALESCE(s.distance_score, 0) * 0.6 + COALESCE(s.interest_score, 0) * 0.4)::float AS recommendation_score
  FROM
    scores s
  ORDER BY
    recommendation_score DESC
  LIMIT 20;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- =====================================================================
-- 9. RPC: get_matches (SECURITY DEFINER)
--    Retorna todos os matches do usuário com informações do outro perfil
-- =====================================================================
CREATE OR REPLACE FUNCTION get_matches(p_user_id uuid)
RETURNS TABLE (
  match_id bigint,
  other_user_id uuid,
  other_user_full_name text,
  other_user_avatar_url text
) AS $$
BEGIN
  RETURN QUERY
  SELECT
    m.id AS match_id,
    CASE
      WHEN m.user1_id = p_user_id THEN m.user2_id
      ELSE m.user1_id
    END AS other_user_id,
    p.full_name AS other_user_full_name,
    p.avatar_url AS other_user_avatar_url
  FROM
    public.matches m
  JOIN
    public.profiles p ON p.id = (
      CASE
        WHEN m.user1_id = p_user_id THEN m.user2_id
        ELSE m.user1_id
      END
    )
  WHERE
    (m.user1_id = p_user_id OR m.user2_id = p_user_id)
  ORDER BY
    m.created_at DESC;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

